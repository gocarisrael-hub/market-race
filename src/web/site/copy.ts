/** Picks the wording for the grammatical form of the honoree. A group defaults to the plural. */
export const byForm = (
  form: SiteForm | null | undefined,
  she: string,
  he: string,
  couple: string,
  group = couple,
) => (form === 'he' ? he : form === 'couple' ? couple : form === 'group' ? group : she)

