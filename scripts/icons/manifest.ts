// Writes the icon manifest from the WebP files in assets/icons and the Hebrew labels in labels-he.json.
//
//     node scripts/icons/manifest.ts
//
// Keys are the file path without the extension: "food/falafel-cone" for the library, a bare name
// ("falafel") for the original map illustrations at the top of assets/icons. Theme folders (the
// recolored originals) are not part of the library. Fails when an icon has no label, so a new icon
// never ships with an English name in the admin.
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { ICON_CATEGORIES } from '../../src/server/domain/icons.ts'

const root = fileURLToPath(new URL('../..', import.meta.url))
const dir = path.join(root, 'assets/icons')
const labels: Record<string, string> = JSON.parse(
  readFileSync(path.join(root, 'scripts/icons/labels-he.json'), 'utf8'),
)

/** Every library icon on disk, as manifest keys, sorted. */
export function iconFilesOnDisk(): string[] {
  const keys: string[] = []
  const library = new Set<string>(ICON_CATEGORIES.map((c) => c.key))
  for (const f of readdirSync(dir)) {
    const p = path.join(dir, f)
    if (statSync(p).isDirectory()) {
      if (!library.has(f)) continue // a theme's recolored set
      for (const g of readdirSync(p)) if (g.endsWith('.webp')) keys.push(`${f}/${g.slice(0, -5)}`)
    } else if (f.endsWith('.webp')) keys.push(f.slice(0, -5))
  }
  return keys.sort()
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const keys = iconFilesOnDisk()
  const missing = keys.filter((k) => !labels[k])
  if (missing.length) {
    console.error(`No Hebrew label in labels-he.json for: ${missing.join(', ')}`)
    process.exit(1)
  }
  const hash = createHash('sha256')
  for (const k of keys) hash.update(k).update(readFileSync(path.join(dir, `${k}.webp`)))
  const version = hash.digest('hex').slice(0, 8)

  const header = '// Generated by scripts/icons/manifest.ts from assets/icons. Do not edit by hand.\n'
  writeFileSync(
    path.join(root, 'src/server/domain/icon-keys.generated.ts'),
    `${header}// Type-only and tiny: safe to import from the player and the site.\n\n` +
      `/** Changes whenever an icon file changes: part of the icon URL, so icons can be cached for a year. */\n` +
      `export const ICONS_VERSION = '${version}'\n\n` +
      `export type IconKey =\n${keys.map((k) => `  | '${k}'`).join('\n')}\n`,
  )
  const rows = keys.map((k) => {
    const slash = k.indexOf('/')
    const category = slash < 0 ? 'classic' : k.slice(0, slash)
    return `  { key: '${k}', category: '${category}', file: '${k}.webp', label: ${JSON.stringify(labels[k])} },`
  })
  writeFileSync(
    path.join(root, 'src/server/domain/icon-manifest.generated.ts'),
    `${header}// The full library with Hebrew labels, for the admin picker and the server's checks.\n` +
      `import type { IconEntry } from './icons.ts'\n\n` +
      `export const ICON_MANIFEST: readonly IconEntry[] = [\n${rows.join('\n')}\n]\n`,
  )
  console.log(`${keys.length} icons, version ${version}`)
}
