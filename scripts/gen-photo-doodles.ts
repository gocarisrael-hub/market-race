// Writes src/server/photos/doodles.generated.ts: the occasion doodles of src/web/shared/decor.tsx
// as plain SVG strings, so the server (plain node, no JSX) can draw them round game photos.
// usage: npx tsx scripts/gen-photo-doodles.ts   (tests/unit/photo-doodle-frame.test.ts checks it is current)
import { writeFileSync } from 'node:fs'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { DECOR_SETS, DOODLES, Doodle } from '../src/web/shared/decor.tsx'

export const GENERATED_PATH = 'src/server/photos/doodles.generated.ts'

/** The inner markup of one doodle (its paths in a 64x64 box, classes i/a/f/d). */
function inner(name: (typeof DOODLES)[number]) {
  const html = renderToStaticMarkup(createElement(Doodle, { name }))
  const open = '<g filter="url(#doodle-wobble)">'
  const start = html.indexOf(open) + open.length
  const end = html.lastIndexOf('</g>')
  if (start < open.length || end < start) throw new Error(`unexpected markup for ${name}`)
  return html.slice(start, end)
}

/** The doodles and the sets, as the generated module must hold them. */
export function doodleData() {
  return {
    svgs: Object.fromEntries([...DOODLES].sort().map((n) => [n, inner(n)])) as Record<string, string>,
    sets: DECOR_SETS as Record<string, string[]>,
  }
}

export function generate() {
  const { svgs, sets } = doodleData()
  return `// GENERATED by scripts/gen-photo-doodles.ts from src/web/shared/decor.tsx. Do not edit.
// The occasion doodles as SVG markup in a 64x64 box: ink lines (i), accent lines (a), light
// accent fills with an ink outline (f) and solid accent dots (d).
export const DOODLE_SVG: Record<string, string> = ${JSON.stringify(svgs, null, 2)}

/** The doodles of each occasion set (decor), in the order screens place them. */
export const DECOR_DOODLES: Record<string, string[]> = ${JSON.stringify(sets, null, 2)}
`
}

if (process.argv[1]?.endsWith('gen-photo-doodles.ts')) {
  writeFileSync(GENERATED_PATH, generate())
  console.log(`wrote ${GENERATED_PATH} (run npm run format)`)
}
